# 3.2 첫 프로그램: print, 주석, 실행 순서
# 위에서 아래로 한 줄씩 실행됩니다.

print("안녕하세요")            # 화면에 글자를 보여 주는 함수
print("두 번째 줄입니다")      # 이 줄은 위 줄이 끝난 뒤에 실행됩니다
# 이 줄은 주석입니다. 파이썬은 # 뒤를 읽지 않습니다.
print(3 + 4)                   # 따옴표가 없으면 계산합니다
print("3 + 4")                 # 따옴표가 있으면 글자 그대로 보여 줍니다
print("사건번호:", "2099가합1234")   # 쉼표로 여러 개를 이어서 보여 줄 수 있습니다
